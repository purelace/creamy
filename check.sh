#!/usr/bin/env bash

# Включаем режим, при котором скрипт завершается, если внутри пайплайна что-то упало
set -eo pipefail

echo "🔍 Поиск локальных пакетов в Workspace..."

# Получаем список имен ТОЛЬКО локальных пакетов текущего воркспейса
# (Игнорируем внешние зависимости из crates.io)
packages=$(cargo metadata --format-version 1 --no-deps | jq -r '.workspace_members[]' | cut -d' ' -f1)

# Проверяем, удалось ли найти пакеты
if [ -z "$packages" ]; then
    echo "❌ Локальные пакеты не найдены или cargo metadata завершился с ошибкой."
    exit 1
fi

# Итерация по каждому пакету
for pkg in $packages; do
    echo "--------------------------------------------------"
    echo "🔨 Запуск cargo check для пакета: [$pkg]..."
    echo "--------------------------------------------------"

    # Запускаем проверку конкретного пакета.
    # Если компиляция упадет, `|| exit 1` мгновенно прервет весь цикл и скрипт.
    cargo check -p "$pkg" || {
        echo -e "\n❌ Ошибка! Проверка пакета [$pkg] завершилась неудачно."
        echo "🛑 Итерация прервана."
        exit 1
    }
done

echo "--------------------------------------------------"
echo "✅ Все локальные пакеты успешно прошли cargo check!"
